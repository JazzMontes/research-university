create or replace function research.ep_profile(u research.users, act text, d jsonb, token text)
returns jsonb language plpgsql
set search_path = research, extensions, pg_temp as $$
declare v_email text; v_avatar text; v_current text; v_new text;
begin
  if act = 'update' then
    v_email := research.opt_text(d, 'email', 254);
    perform research.valid_email(v_email);
    if v_email <> '' and exists (select 1 from research.users where lower(email) = lower(v_email) and id <> u.id) then
      perform research.fail(409, 'Ese correo ya lo usa otra cuenta.');
    end if;
    -- Foto: imagen pequeña (la app la recorta y comprime antes de enviarla).
    v_avatar := coalesce(d ->> 'avatar', u.avatar, '');
    if v_avatar <> '' and (length(v_avatar) > 400000 or v_avatar !~ '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$') then
      perform research.fail(422, 'La foto no es válida o es demasiado grande. Usa una imagen JPG o PNG.');
    end if;
    update research.users set name = research.req_text(d, 'name', 150), email = nullif(v_email, ''),
      avatar = nullif(v_avatar, ''), updated_at = now() where id = u.id;
  elsif act = 'change-password' then
    v_current := coalesce(d ->> 'current_password', '');
    v_new := coalesce(d ->> 'new_password', '');
    if not research.check_password(v_current, u.password_hash) then
      perform research.fail(422, 'La contraseña actual no es correcta.');
    end if;
    if not research.valid_password(v_new) then
      perform research.fail(422, 'La nueva contraseña necesita de 8 a 72 caracteres con mayúscula, minúscula y número.');
    end if;
    if v_new = v_current then perform research.fail(422, 'La nueva contraseña debe ser distinta de la actual.'); end if;
    update research.users set password_hash = research.hash_password(v_new), must_change_password = 0, updated_at = now() where id = u.id;
    -- Cierra las demás sesiones abiertas (otros dispositivos); esta sigue activa.
    update research.user_sessions set revoked_at = now()
      where user_id = u.id and revoked_at is null and token_hash <> research.sha256(coalesce(token, ''));
  else
    perform research.fail(404, 'Operación no disponible.');
  end if;
  select * into u from research.users where id = u.id;
  return research.ok(jsonb_build_object('user', research.public_user(u)));
end $$;

-- ------------------------------------------------------------------
-- Recuperar contraseña por correo
-- ------------------------------------------------------------------
-- Solo la llama la función Edge con la clave secreta (nunca la app): devuelve el código para enviarlo.
create or replace function public.research_password_reset_issue(identifier text)
returns jsonb language plpgsql
security definer
set search_path = research, extensions, pg_temp as $$
declare u research.users; code text;
begin
  -- Se recupera con el correo registrado; el correo incluye el usuario por si se olvidó.
  select * into u from research.users
    where deleted_at is null and lower(email) = lower(btrim(identifier)) order by (status = 'active') desc, id limit 1;
  if u.id is null then return jsonb_build_object('result', 'not_found'); end if;
  if u.status <> 'active' then return jsonb_build_object('result', 'inactive'); end if;
  if exists (select 1 from research.password_resets where user_id = u.id and created_at > now() - interval '60 seconds') then
    return jsonb_build_object('result', 'wait');
  end if;
  -- Código de 6 dígitos con números aleatorios seguros.
  code := lpad(((('x' || encode(extensions.gen_random_bytes(4), 'hex'))::bit(32)::bigint % 1000000))::text, 6, '0');
  update research.password_resets set used_at = now() where user_id = u.id and used_at is null;
  insert into research.password_resets (user_id, code_hash, expires_at)
    values (u.id, research.sha256(u.id || ':' || code), now() + interval '15 minutes');
  return jsonb_build_object('result', 'ok', 'email', u.email, 'name', u.name, 'username', u.username, 'code', code);
end $$;
revoke all on function public.research_password_reset_issue(text) from public;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on function public.research_password_reset_issue(text) from anon;
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on function public.research_password_reset_issue(text) from authenticated;
  end if;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant execute on function public.research_password_reset_issue(text) to service_role;
  end if;
end $$;

-- Pública (sin sesión): código + nueva contraseña.
create or replace function research.auth_reset_password(d jsonb)
returns jsonb language plpgsql
set search_path = research, extensions, pg_temp as $$
declare u research.users; r research.password_resets; v_code text; v_new text;
begin
  select * into u from research.users
    where status = 'active' and (lower(username) = lower(btrim(coalesce(d ->> 'identifier', '')))
                                 or lower(email) = lower(btrim(coalesce(d ->> 'identifier', ''))))
    order by (lower(username) = lower(btrim(coalesce(d ->> 'identifier', '')))) desc limit 1;
  v_code := regexp_replace(coalesce(d ->> 'code', ''), '\D', '', 'g');
  v_new := coalesce(d ->> 'password', '');
  if u.id is not null then
    select * into r from research.password_resets where user_id = u.id and used_at is null and expires_at > now()
      order by id desc limit 1 for update;
  end if;
  if r.id is null then perform research.fail(422, 'El código no es válido o ya venció. Pide uno nuevo.'); end if;
  if r.attempts >= 5 then
    update research.password_resets set used_at = now() where id = r.id;
    perform research.fail(422, 'Demasiados intentos. Pide un código nuevo.');
  end if;
  if r.code_hash <> research.sha256(u.id || ':' || v_code) then
    update research.password_resets set attempts = attempts + 1 where id = r.id;
    return research.ok(jsonb_build_object('message', 'El código no es correcto. Revisa el correo e inténtalo de nuevo.'), 422);
  end if;
  if not research.valid_password(v_new) then
    perform research.fail(422, 'La nueva contraseña necesita de 8 a 72 caracteres con mayúscula, minúscula y número.');
  end if;
  update research.password_resets set used_at = now() where id = r.id;
  update research.users set password_hash = research.hash_password(v_new), must_change_password = 0, updated_at = now() where id = u.id;
  update research.user_sessions set revoked_at = now() where user_id = u.id and revoked_at is null;
  return research.ok(jsonb_build_object('message', 'Contraseña actualizada. Ya puedes iniciar sesión.', 'username', u.username));
end $$;

-- ------------------------------------------------------------------
-- Historial de chats del asistente (cada quien ve solo los suyos)
-- ------------------------------------------------------------------
create or replace function research.ep_chats(u research.users, act text, d jsonb)
returns jsonb language plpgsql
set search_path = research, extensions, pg_temp as $$
declare c research.assistant_chats; cid integer; v_question text; v_answer text;
begin
  if act = 'chats' then
    return research.ok(jsonb_build_object('items', (
      select coalesce(jsonb_agg(jsonb_build_object('id', x.id, 'title', x.title, 'created_at', x.created_at, 'updated_at', x.updated_at)
                                order by x.updated_at desc), '[]')
      from (select * from research.assistant_chats where user_id = u.id order by updated_at desc limit 100) x)));
  end if;

  if act = 'chat-save' then
    v_question := research.req_text(d, 'question', 20000);
    v_answer := research.req_text(d, 'answer', 60000);
    if research.has(d, 'chat_id') then
      select * into c from research.assistant_chats where id = research.req_id(d, 'chat_id') and user_id = u.id for update;
    end if;
    if c.id is null then
      insert into research.assistant_chats (user_id, title)
        values (u.id, research.cut(regexp_replace(v_question, '\s+', ' ', 'g'), 80)) returning * into c;
    end if;
    insert into research.assistant_messages (chat_id, author, text, attachment)
      values (c.id, 'user', v_question, nullif(research.opt_text(d, 'attachment', 255), ''));
    insert into research.assistant_messages (chat_id, author, text, sources)
      values (c.id, 'assistant', v_answer, case when jsonb_typeof(d -> 'sources') = 'array' then d -> 'sources' else '[]'::jsonb end);
    update research.assistant_chats set updated_at = now() where id = c.id;
    return research.ok(jsonb_build_object('chat_id', c.id, 'title', c.title));
  end if;

  cid := research.req_id(d, 'chat_id');
  select * into c from research.assistant_chats where id = cid and user_id = u.id;
  if c.id is null then perform research.fail(404, 'Ese chat ya no existe.'); end if;

  if act = 'chat-messages' then
    return research.ok(jsonb_build_object('chat', to_jsonb(c) - 'user_id', 'items', (
      select coalesce(jsonb_agg(jsonb_build_object('author', m.author, 'text', m.text, 'sources', m.sources,
                                                   'attachment', m.attachment, 'created_at', m.created_at) order by m.id), '[]')
      from research.assistant_messages m where m.chat_id = cid)));
  elsif act = 'chat-delete' then
    delete from research.assistant_chats where id = cid;
    return research.ok(jsonb_build_object('deleted', cid));
  end if;
  perform research.fail(404, 'Operación no disponible.');
  return null;
end $$;


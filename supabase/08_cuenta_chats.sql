-- =====================================================================
-- URPMP · 08 · Mi cuenta (perfil, foto, contraseña) e historial de chats del asistente
--  * Coordinación crea la cuenta con una contraseña TEMPORAL: al primer inicio
--    la persona debe cambiarla (must_change_password). Lo mismo si Coordinación
--    la restablece.
--  * Cada persona edita su nombre, correo y foto, y cambia su propia contraseña.
--  * "Olvidé mi contraseña": la función Edge "asistente" pide un código a
--    research_password_reset_issue (solo con la clave secreta del servidor) y lo
--    manda por correo; la persona lo escribe en la app con su nueva contraseña.
--  * Historial de chats del asistente: se guarda por persona y se puede borrar.
-- =====================================================================

-- Las columnas users.must_change_password y users.avatar se crean en 01_esquema.sql.

create table if not exists research.password_resets (
  id          integer generated by default as identity primary key,
  user_id     integer not null references research.users(id) on delete cascade,
  code_hash   char(64) not null,
  attempts    smallint not null default 0,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  used_at     timestamptz
);
create index if not exists password_resets_user_idx on research.password_resets (user_id, created_at desc);

create table if not exists research.assistant_chats (
  id          integer generated by default as identity primary key,
  user_id     integer not null references research.users(id) on delete cascade,
  title       varchar(120) not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists assistant_chats_user_idx on research.assistant_chats (user_id, updated_at desc);

create table if not exists research.assistant_messages (
  id          integer generated by default as identity primary key,
  chat_id     integer not null references research.assistant_chats(id) on delete cascade,
  author      varchar(10) not null check (author in ('user', 'assistant')),
  text        text not null,
  sources     jsonb not null default '[]'::jsonb,
  attachment  varchar(255),
  created_at  timestamptz not null default now()
);
create index if not exists assistant_messages_chat_idx on research.assistant_messages (chat_id, id);

alter table research.password_resets    enable row level security;
alter table research.assistant_chats    enable row level security;
alter table research.assistant_messages enable row level security;

-- ------------------------------------------------------------------
-- Mi cuenta
-- ------------------------------------------------------------------
create or replace function research.ep_profile(u research.users, act text, d jsonb, token text)
returns jsonb language plpgsql
set search_path = research, extensions, pg_temp as $$
declare v_email text; v_avatar text; v_current text; v_new text;
begin
  if act = 'update' then
    v_email := research.opt_text(d, 'email', 254);
    perform research.valid_email(v_email);
    if v_email <> '' and exists (select 1 from research.users where lower(email) = lower(v_email) and id <> u.id) then
      perform research.fail(409, 'Ese correo ya lo usa otra cuenta.');
    end if;
    -- Foto: imagen pequeña (la app la recorta y comprime antes de enviarla).
    v_avatar := coalesce(d ->> 'avatar', u.avatar, '');
    if v_avatar <> '' and (length(v_avatar) > 400000 or v_avatar !~ '^data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/=]+$') then
      perform research.fail(422, 'La foto no es válida o es demasiado grande. Usa una imagen JPG o PNG.');
    end if;
    update research.users set name = research.req_text(d, 'name', 150), email = nullif(v_email, ''),
      avatar = nullif(v_avatar, ''), updated_at = now() where id = u.id;
  elsif act = 'change-password' then
    v_current := coalesce(d ->> 'current_password', '');
    v_new := coalesce(d ->> 'new_password', '');
    if not research.check_password(v_current, u.password_hash) then
      perform research.fail(422, 'La contraseña actual no es correcta.');
    end if;
    if not research.valid_password(v_new) then
      perform research.fail(422, 'La nueva contraseña necesita de 8 a 72 caracteres con mayúscula, minúscula y número.');
    end if;
    if v_new = v_current then perform research.fail(422, 'La nueva contraseña debe ser distinta de la actual.'); end if;
    update research.users set password_hash = research.hash_password(v_new), must_change_password = 0, updated_at = now() where id = u.id;
    -- Cierra las demás sesiones abiertas (otros dispositivos); esta sigue activa.
    update research.user_sessions set revoked_at = now()
      where user_id = u.id and revoked_at is null and token_hash <> research.sha256(coalesce(token, ''));
  else
    perform research.fail(404, 'Operación no disponible.');
  end if;
  select * into u from research.users where id = u.id;
  return research.ok(jsonb_build_object('user', research.public_user(u)));
end $$;

-- ------------------------------------------------------------------
-- Recuperar contraseña por correo
-- ------------------------------------------------------------------
-- Solo la llama la función Edge con la clave secreta (nunca la app): devuelve el código para enviarlo.
create or replace function public.research_password_reset_issue(identifier text)
returns jsonb language plpgsql
security definer
set search_path = research, extensions, pg_temp as $$
declare u research.users; code text;
begin
  select * into u from research.users
    where status = 'active' and (lower(username) = lower(btrim(identifier)) or lower(email) = lower(btrim(identifier)))
    order by (lower(username) = lower(btrim(identifier))) desc limit 1;
  if u.id is null then return jsonb_build_object('result', 'not_found'); end if;
  if u.email is null or btrim(u.email) = '' then return jsonb_build_object('result', 'no_email'); end if;
  if exists (select 1 from research.password_resets where user_id = u.id and created_at > now() - interval '60 seconds') then
    return jsonb_build_object('result', 'wait');
  end if;
  -- Código de 6 dígitos con números aleatorios seguros.
  code := lpad(((('x' || encode(extensions.gen_random_bytes(4), 'hex'))::bit(32)::bigint % 1000000))::text, 6, '0');
  update research.password_resets set used_at = now() where user_id = u.id and used_at is null;
  insert into research.password_resets (user_id, code_hash, expires_at)
    values (u.id, research.sha256(u.id || ':' || code), now() + interval '15 minutes');
  return jsonb_build_object('result', 'ok', 'email', u.email, 'name', u.name, 'code', code);
end $$;
revoke all on function public.research_password_reset_issue(text) from public;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on function public.research_password_reset_issue(text) from anon;
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on function public.research_password_reset_issue(text) from authenticated;
  end if;
  if exists (select 1 from pg_roles where rolname = 'service_role') then
    grant execute on function public.research_password_reset_issue(text) to service_role;
  end if;
end $$;

-- Pública (sin sesión): código + nueva contraseña.
create or replace function research.auth_reset_password(d jsonb)
returns jsonb language plpgsql
set search_path = research, extensions, pg_temp as $$
declare u research.users; r research.password_resets; v_code text; v_new text;
begin
  select * into u from research.users
    where status = 'active' and (lower(username) = lower(btrim(coalesce(d ->> 'identifier', '')))
                                 or lower(email) = lower(btrim(coalesce(d ->> 'identifier', ''))))
    order by (lower(username) = lower(btrim(coalesce(d ->> 'identifier', '')))) desc limit 1;
  v_code := regexp_replace(coalesce(d ->> 'code', ''), '\D', '', 'g');
  v_new := coalesce(d ->> 'password', '');
  if u.id is not null then
    select * into r from research.password_resets where user_id = u.id and used_at is null and expires_at > now()
      order by id desc limit 1 for update;
  end if;
  if r.id is null then perform research.fail(422, 'El código no es válido o ya venció. Pide uno nuevo.'); end if;
  if r.attempts >= 5 then
    update research.password_resets set used_at = now() where id = r.id;
    perform research.fail(422, 'Demasiados intentos. Pide un código nuevo.');
  end if;
  if r.code_hash <> research.sha256(u.id || ':' || v_code) then
    update research.password_resets set attempts = attempts + 1 where id = r.id;
    return research.ok(jsonb_build_object('message', 'El código no es correcto. Revisa el correo e inténtalo de nuevo.'), 422);
  end if;
  if not research.valid_password(v_new) then
    perform research.fail(422, 'La nueva contraseña necesita de 8 a 72 caracteres con mayúscula, minúscula y número.');
  end if;
  update research.password_resets set used_at = now() where id = r.id;
  update research.users set password_hash = research.hash_password(v_new), must_change_password = 0, updated_at = now() where id = u.id;
  update research.user_sessions set revoked_at = now() where user_id = u.id and revoked_at is null;
  return research.ok(jsonb_build_object('message', 'Contraseña actualizada. Ya puedes iniciar sesión.'));
end $$;

-- ------------------------------------------------------------------
-- Historial de chats del asistente (cada quien ve solo los suyos)
-- ------------------------------------------------------------------
create or replace function research.ep_chats(u research.users, act text, d jsonb)
returns jsonb language plpgsql
set search_path = research, extensions, pg_temp as $$
declare c research.assistant_chats; cid integer; v_question text; v_answer text;
begin
  if act = 'chats' then
    return research.ok(jsonb_build_object('items', (
      select coalesce(jsonb_agg(jsonb_build_object('id', x.id, 'title', x.title, 'created_at', x.created_at, 'updated_at', x.updated_at)
                                order by x.updated_at desc), '[]')
      from (select * from research.assistant_chats where user_id = u.id order by updated_at desc limit 100) x)));
  end if;

  if act = 'chat-save' then
    v_question := research.req_text(d, 'question', 20000);
    v_answer := research.req_text(d, 'answer', 60000);
    if research.has(d, 'chat_id') then
      select * into c from research.assistant_chats where id = research.req_id(d, 'chat_id') and user_id = u.id for update;
    end if;
    if c.id is null then
      insert into research.assistant_chats (user_id, title)
        values (u.id, research.cut(regexp_replace(v_question, '\s+', ' ', 'g'), 80)) returning * into c;
    end if;
    insert into research.assistant_messages (chat_id, author, text, attachment)
      values (c.id, 'user', v_question, nullif(research.opt_text(d, 'attachment', 255), ''));
    insert into research.assistant_messages (chat_id, author, text, sources)
      values (c.id, 'assistant', v_answer, case when jsonb_typeof(d -> 'sources') = 'array' then d -> 'sources' else '[]'::jsonb end);
    update research.assistant_chats set updated_at = now() where id = c.id;
    return research.ok(jsonb_build_object('chat_id', c.id, 'title', c.title));
  end if;

  cid := research.req_id(d, 'chat_id');
  select * into c from research.assistant_chats where id = cid and user_id = u.id;
  if c.id is null then perform research.fail(404, 'Ese chat ya no existe.'); end if;

  if act = 'chat-messages' then
    return research.ok(jsonb_build_object('chat', to_jsonb(c) - 'user_id', 'items', (
      select coalesce(jsonb_agg(jsonb_build_object('author', m.author, 'text', m.text, 'sources', m.sources,
                                                   'attachment', m.attachment, 'created_at', m.created_at) order by m.id), '[]')
      from research.assistant_messages m where m.chat_id = cid)));
  elsif act = 'chat-delete' then
    delete from research.assistant_chats where id = cid;
    return research.ok(jsonb_build_object('deleted', cid));
  end if;
  perform research.fail(404, 'Operación no disponible.');
  return null;
end $$;

-- =====================================================================
-- Solicitudes de cambio de investigador responsable
-- El estudiante (o cualquier integrante que no sea el responsable) explica el motivo;
-- Coordinación aprueba eligiendo al nuevo investigador, o rechaza con una nota.
-- =====================================================================
create or replace function research.change_request_json(c research.researcher_change_requests)
returns jsonb language sql stable
set search_path = research, extensions, pg_temp as $$
  select to_jsonb(c) || jsonb_build_object(
    'requester_name', (select name from research.users where id = c.requested_by),
    'current_name', (select name from research.users where id = c.current_researcher_id),
    'proposed_name', (select name from research.users where id = c.proposed_researcher_id),
    'reviewer_name', (select name from research.users where id = c.reviewed_by),
    'target_title', coalesce((select title from research.projects where id = c.project_id), (select title from research.proposals where id = c.proposal_id)),
    'target_kind', case when c.project_id is not null then 'project' else 'proposal' end,
    'link', case when c.project_id is not null then 'projects/' || c.project_id else 'proposals/' || c.proposal_id end);
$$;

create or replace function research.ep_changes(u research.users, act text, d jsonb)
returns jsonb language plpgsql
set search_path = research, extensions, pg_temp as $$
declare c research.researcher_change_requests; p research.projects; pr research.proposals; rid integer; decision text; note text;
begin
  if act = 'list' then
    return research.ok(jsonb_build_object('items', (
      select coalesce(jsonb_agg(research.change_request_json(x) order by x.id desc), '[]') from research.researcher_change_requests x
      where (u.role = 'coordinator' and x.status = 'pending') or x.requested_by = u.id)));
  end if;

  if act = 'request' then
    if research.has(d, 'project_id') then
      select * into p from research.projects where id = research.req_id(d, 'project_id') for update;
      if p.id is null or not exists (select 1 from research.participants t where t.project_id = p.id and t.user_id = u.id and t.is_active = 1) then
        perform research.fail(404, 'Proyecto no disponible.');
      end if;
      if p.status not in ('active', 'changes', 'closing') then perform research.fail(409, 'El proyecto ya está cerrado.'); end if;
      if p.responsible_researcher_id = u.id then perform research.fail(409, 'Ya eres el investigador responsable.'); end if;
      if exists (select 1 from research.researcher_change_requests where project_id = p.id and status = 'pending') then
        perform research.fail(409, 'Ya hay una solicitud de cambio pendiente para este proyecto.');
      end if;
    else
      select * into pr from research.proposals where id = research.req_id(d, 'proposal_id') for update;
      if pr.id is null or pr.author_id <> u.id then perform research.fail(404, 'Propuesta no disponible.'); end if;
      if pr.status in ('approved', 'rejected', 'cancelled') then perform research.fail(409, 'La propuesta ya está cerrada.'); end if;
      if pr.responsible_researcher_id = u.id then perform research.fail(409, 'Ya eres el investigador responsable.'); end if;
      if exists (select 1 from research.researcher_change_requests where proposal_id = pr.id and status = 'pending') then
        perform research.fail(409, 'Ya hay una solicitud de cambio pendiente para esta propuesta.');
      end if;
    end if;
    note := research.req_text(d, 'reason', 2000);
    if length(btrim(note)) < 10 then perform research.fail(422, 'Explica el motivo con un poco más de detalle.'); end if;
    rid := case when research.has(d, 'proposed_researcher_id') then research.req_id(d, 'proposed_researcher_id') end;
    if rid is not null then perform research.active_role(rid, 'researcher'); end if;
    insert into research.researcher_change_requests (project_id, proposal_id, requested_by, current_researcher_id, proposed_researcher_id, reason)
      values (p.id, pr.id, u.id, coalesce(p.responsible_researcher_id, pr.responsible_researcher_id), rid, note)
      returning * into c;
    return research.ok(jsonb_build_object('request', research.change_request_json(c)), 201);
  end if;

  if act = 'review' then
    if u.role <> 'coordinator' then perform research.fail(403, 'Solo Coordinación resuelve las solicitudes.'); end if;
    select * into c from research.researcher_change_requests where id = research.req_id(d, 'request_id') for update;
    if c.id is null then perform research.fail(404, 'Solicitud no encontrada.'); end if;
    if c.status <> 'pending' then perform research.fail(409, 'Esa solicitud ya se resolvió.'); end if;
    decision := research.req_text(d, 'decision', 20);
    if decision not in ('approved', 'rejected') then perform research.fail(422, 'Decisión inválida.'); end if;
    note := case when decision = 'rejected' then research.req_text(d, 'note', 2000) else research.opt_text(d, 'note', 2000) end;
    if decision = 'approved' then
      rid := coalesce(case when research.has(d, 'researcher_id') then research.req_id(d, 'researcher_id') end, c.proposed_researcher_id);
      if rid is null then perform research.fail(422, 'Elige al nuevo investigador responsable.'); end if;
      if c.project_id is not null then
        select * into p from research.projects where id = c.project_id for update;
        perform research.project_set_researcher(p, rid, u.id, 'Solicitud de ' || (select name from research.users where id = c.requested_by) || ': ' || c.reason);
      else
        select * into pr from research.proposals where id = c.proposal_id for update;
        perform research.proposal_set_researcher(pr, rid, u.id, c.reason);
      end if;
    end if;
    update research.researcher_change_requests set status = decision, reviewed_by = u.id, review_note = nullif(note, ''),
      reviewed_at = now(), proposed_researcher_id = coalesce(rid, proposed_researcher_id) where id = c.id returning * into c;
    return research.ok(jsonb_build_object('request', research.change_request_json(c)));
  end if;
  perform research.fail(404, 'Operación no disponible.');
  return null;
end $$;

-- =====================================================================
-- Notificaciones (campanita). Se generan solas a partir de lo que pasa en la plataforma.
-- =====================================================================
create or replace function research.notify(uids integer[], v_title text, v_body text, v_link text, v_tone text default 'progress', v_key text default null)
returns void language sql
set search_path = research, extensions, pg_temp as $$
  insert into research.notifications (user_id, title, body, link, tone, dedupe_key)
  select distinct x, left(v_title, 200), v_body, v_link, v_tone, v_key
  from unnest(uids) x join research.users us on us.id = x and us.status = 'active' and us.deleted_at is null
  where x is not null
  on conflict (user_id, dedupe_key) where dedupe_key is not null do nothing;
$$;

create or replace function research.team_ids(pid integer)
returns integer[] language sql stable
set search_path = research, extensions, pg_temp as $$
  select coalesce(array_agg(distinct x), '{}') from (
    select user_id x from research.participants where project_id = pid and is_active = 1
    union select responsible_researcher_id from research.projects where id = pid) s;
$$;

create or replace function research.coordinator_ids()
returns integer[] language sql stable
set search_path = research, extensions, pg_temp as $$
  select coalesce(array_agg(id), '{}') from research.users where role = 'coordinator' and status = 'active' and deleted_at is null;
$$;

create or replace function research.trg_project_event()
returns trigger language plpgsql
set search_path = research, extensions, pg_temp as $$
declare p research.projects; a research.activities; det jsonb; others integer[]; t text; link text;
begin
  select * into p from research.projects where id = new.project_id;
  begin det := coalesce(new.details::jsonb, '{}'); exception when others then det := '{}'; end;
  others := array_remove(research.team_ids(p.id), new.actor_id);
  t := p.title;
  link := 'projects/' || p.id;
  if new.entity = 'activity' then
    select * into a from research.activities where id = new.entity_id;
    if new.action in ('create', 'reassign') and a.participant_id <> new.actor_id then
      perform research.notify(array[a.participant_id], 'Nueva actividad asignada: ' || left(a.description, 120),
        'Proyecto «' || t || '» · vence el ' || to_char(a.deadline, 'DD/MM/YYYY'), 'activities/' || a.id, 'progress');
    elsif new.action = 'submit' then
      perform research.notify(array_remove(array[p.responsible_researcher_id], new.actor_id), 'Entrega por revisar: ' || left(a.description, 120),
        (select name from research.users where id = new.actor_id) || ' la entregó en «' || t || '».', 'activities/' || a.id, 'progress');
    elsif new.action = 'review' then
      perform research.notify(array_remove(array[a.participant_id], new.actor_id),
        case when det -> 'input' ->> 'decision' = 'approved' then '✓ Aceptaron tu actividad: ' else 'Te pidieron cambios en: ' end || left(a.description, 120),
        'Proyecto «' || t || '»' || coalesce(' · ' || nullif(det -> 'input' ->> 'observations', ''), ''), 'activities/' || a.id,
        case when det -> 'input' ->> 'decision' = 'approved' then 'done' else 'changes' end);
    elsif new.action = 'cancel' then
      perform research.notify(array_remove(array[a.participant_id], new.actor_id), 'Se canceló la actividad: ' || left(a.description, 120),
        'Proyecto «' || t || '»', 'activities/' || a.id, 'cancelled');
    end if;
  elsif new.entity = 'participant' then
    if new.action = 'add' then
      perform research.notify(array_remove(array[new.entity_id], new.actor_id), 'Te agregaron al proyecto «' || t || '»', null, link, 'done');
    elsif new.action = 'remove' then
      perform research.notify(array_remove(array[new.entity_id], new.actor_id), 'Ya no participas en el proyecto «' || t || '»', null, null, 'cancelled');
    end if;
  elsif new.entity = 'closure' then
    if new.action = 'request' then
      perform research.notify(research.coordinator_ids(), 'Solicitud de cierre: «' || t || '»', 'Revisa el proyecto para aprobar el cierre o pedir cambios.', link, 'progress');
    elsif det -> 'input' ->> 'decision' = 'approved' then
      perform research.notify(others, '🎉 El proyecto «' || t || '» se completó', null, link, 'done');
    else
      perform research.notify(array_remove(array[p.responsible_researcher_id], new.actor_id), 'Coordinación pidió cambios para cerrar «' || t || '»',
        det -> 'input' ->> 'observations', link, 'changes');
    end if;
  elsif new.entity = 'project' then
    if new.action = 'created_from_proposal' then
      perform research.notify(others, 'Se creó el proyecto «' || t || '»', 'La propuesta fue aprobada. ¡Manos a la obra!', link, 'done');
    elsif new.action = 'cancelled' then
      perform research.notify(others, 'El proyecto «' || t || '» fue cancelado', det ->> 'reason', link, 'cancelled');
    elsif new.action = 'reopened' then
      perform research.notify(others, 'Se reabrió el proyecto «' || t || '»', det ->> 'reason', link, 'progress');
    elsif new.action = 'change-researcher' then
      perform research.notify(others, 'Nuevo investigador responsable en «' || t || '»', (det ->> 'before') || ' → ' || (det ->> 'after'), link, 'changes');
    end if;
  elsif new.entity = 'document' and new.action in ('upload', 'upload-version') then
    perform research.notify(others, case when new.action = 'upload' then 'Nuevo documento en «' else 'Nueva versión de documento en «' end || t || '»',
      det ->> 'title', link || '?tab=Documentos', 'progress');
  end if;
  return null;
end $$;

create or replace function research.trg_proposal_event()
returns trigger language plpgsql
set search_path = research, extensions, pg_temp as $$
declare x research.proposals; link text; t text;
begin
  select * into x from research.proposals where id = new.proposal_id;
  link := 'proposals/' || x.id; t := x.title;
  if new.new_status = 'pending_researcher_review' and new.action in ('created', 'resubmit', 'reactivated', 'researcher_changed') then
    perform research.notify(array_remove(array[x.responsible_researcher_id], new.actor_id), 'Propuesta por revisar: «' || t || '»',
      (select name from research.users where id = x.author_id) || ' te eligió como investigador responsable.', link, 'progress');
  elsif new.new_status = 'pending_coordinator' and new.action in ('created', 'resubmit', 'reactivated', 'review_approved') then
    perform research.notify(array_remove(research.coordinator_ids(), new.actor_id), 'Propuesta esperando decisión: «' || t || '»', null, link, 'progress');
  end if;
  if new.action = 'review_approved' then
    perform research.notify(array_remove(array[x.author_id], new.actor_id),
      case when new.new_status = 'approved' then '🎉 ¡Aprobaron tu propuesta «' || t || '»!' else 'Tu propuesta «' || t || '» pasó a Coordinación' end,
      new.details, link, 'done');
  elsif new.action = 'review_changes_requested' then
    perform research.notify(array_remove(array[x.author_id], new.actor_id), 'Te pidieron cambios en «' || t || '»', new.details, link, 'changes');
  elsif new.action = 'review_rejected' then
    perform research.notify(array_remove(array[x.author_id], new.actor_id), 'Tu propuesta «' || t || '» fue rechazada', new.details, link, 'cancelled');
  elsif new.action = 'cancelled' then
    perform research.notify(array_remove(array[x.author_id, x.responsible_researcher_id], new.actor_id), 'Se canceló la propuesta «' || t || '»', new.details, link, 'cancelled');
  elsif new.action = 'researcher_changed' then
    perform research.notify(array_remove(array[x.author_id], new.actor_id), 'Cambió el investigador responsable de «' || t || '»', new.details, link, 'changes');
  end if;
  return null;
end $$;

create or replace function research.trg_change_request()
returns trigger language plpgsql
set search_path = research, extensions, pg_temp as $$
declare j jsonb := research.change_request_json(new);
begin
  if tg_op = 'INSERT' then
    perform research.notify(research.coordinator_ids(), 'Solicitud de cambio de investigador: «' || (j ->> 'target_title') || '»',
      (j ->> 'requester_name') || ': ' || left(new.reason, 200), 'dashboard', 'progress');
  elsif new.status <> old.status then
    perform research.notify(array[new.requested_by],
      case when new.status = 'approved' then 'Aprobaron tu solicitud de cambio de investigador' else 'Rechazaron tu solicitud de cambio de investigador' end,
      coalesce(new.review_note, j ->> 'target_title'), j ->> 'link', case when new.status = 'approved' then 'done' else 'cancelled' end);
  end if;
  return null;
end $$;


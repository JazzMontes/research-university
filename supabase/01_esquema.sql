-- =====================================================================
-- URPMP · 01 · Esquema de datos (PostgreSQL / Supabase)
-- Todo vive en el esquema privado "research". La app NUNCA lee las tablas
-- directamente: solo llama a public.research_api (archivo 07).
-- Se puede ejecutar varias veces: no borra datos.
-- =====================================================================

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create extension if not exists unaccent with schema extensions;

create schema if not exists research;

-- Las funciones se recrean siempre (no guardan datos): se borran las de versiones anteriores.
do $$
declare r record;
begin
  for r in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'research' loop
    execute 'drop function if exists ' || r.sig || ' cascade';
  end loop;
end $$;
drop function if exists public.research_api(text, text, jsonb, text);

create table if not exists research.users (
  id            integer generated by default as identity primary key,
  name          varchar(150) not null,
  username      varchar(80)  not null,
  email         varchar(254),
  password_hash varchar(255) not null,
  role          varchar(20)  not null check (role in ('student','researcher','evaluator','coordinator')),
  status        varchar(10)  not null default 'active' check (status in ('active','inactive')),
  created_at    timestamptz  not null default now(),
  updated_at    timestamptz  not null default now()
);
create unique index if not exists users_username_lower_uq on research.users (lower(username));

create table if not exists research.user_sessions (
  id               integer generated by default as identity primary key,
  user_id          integer not null references research.users(id),
  token_hash       char(64) not null,
  created_at       timestamptz not null default now(),
  last_activity_at timestamptz not null default now(),
  expires_at       timestamptz not null,
  revoked_at       timestamptz
);
create index if not exists user_sessions_token_idx on research.user_sessions (token_hash);
create index if not exists user_sessions_user_idx on research.user_sessions (user_id);

create table if not exists research.proposals (
  id                          integer generated by default as identity primary key,
  title                       varchar(250) not null,
  description                 text not null,
  objectives                  text not null,
  author_id                   integer not null references research.users(id),
  responsible_researcher_id   integer not null references research.users(id),
  status                      varchar(50) not null,
  is_archived                 smallint not null default 0,
  status_before_archive       varchar(50),
  correction_pending_resubmit smallint not null default 0,
  created_at                  timestamptz not null default now(),
  updated_at                  timestamptz not null default now()
);

create table if not exists research.proposal_history (
  id              integer generated by default as identity primary key,
  proposal_id     integer not null references research.proposals(id),
  actor_id        integer not null references research.users(id),
  action          varchar(80) not null,
  previous_status varchar(50),
  new_status      varchar(50) not null,
  details         text,
  created_at      timestamptz not null default now()
);
create index if not exists proposal_history_proposal_idx on research.proposal_history (proposal_id);

create table if not exists research.proposal_reviews (
  id            integer generated by default as identity primary key,
  proposal_id   integer not null references research.proposals(id),
  researcher_id integer not null references research.users(id),
  decision      varchar(30) not null,
  observations  text,
  created_at    timestamptz not null default now()
);

create table if not exists research.evaluation_assignments (
  id           integer generated by default as identity primary key,
  proposal_id  integer not null references research.proposals(id),
  evaluator_id integer not null references research.users(id),
  assigned_by  integer not null references research.users(id),
  is_active    smallint not null default 1,
  assigned_at  timestamptz not null default now()
);
create index if not exists evaluation_assignments_proposal_idx on research.evaluation_assignments (proposal_id);

create table if not exists research.evaluations (
  id           integer generated by default as identity primary key,
  proposal_id  integer not null references research.proposals(id),
  evaluator_id integer not null references research.users(id),
  decision     varchar(30) not null,
  observations text not null,
  created_at   timestamptz not null default now()
);

create table if not exists research.projects (
  id                        integer generated by default as identity primary key,
  proposal_id               integer not null unique references research.proposals(id),
  title                     varchar(250) not null,
  description               text,
  objectives                text,
  start_date                date,
  end_date                  date,
  responsible_researcher_id integer not null references research.users(id),
  status                    varchar(20) not null default 'active' check (status in ('active','closing','finalized')),
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now()
);
-- Columnas agregadas en la versión 2 (por si la base ya existía).
alter table research.projects add column if not exists description text;
alter table research.projects add column if not exists objectives text;
alter table research.projects add column if not exists start_date date;
alter table research.projects add column if not exists end_date date;

create table if not exists research.participants (
  id           integer generated by default as identity primary key,
  project_id   integer not null references research.projects(id),
  user_id      integer not null references research.users(id),
  project_role varchar(80),
  is_active    smallint not null default 1,
  joined_at    timestamptz not null default now(),
  removed_at   timestamptz,
  unique (project_id, user_id)
);
alter table research.participants add column if not exists project_role varchar(80);

create table if not exists research.activities (
  id             integer generated by default as identity primary key,
  project_id     integer not null references research.projects(id),
  description    text not null,
  participant_id integer not null references research.users(id),
  deadline       date not null,
  status         varchar(20) not null default 'pending' check (status in ('pending','in_progress','in_review','completed')),
  observations   text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists activities_project_idx on research.activities (project_id);

create table if not exists research.milestones (
  id          integer generated by default as identity primary key,
  project_id  integer not null references research.projects(id),
  description text not null,
  target_date date not null,
  status      varchar(20) not null default 'pending' check (status in ('pending','achieved')),
  created_at  timestamptz not null default now()
);

create table if not exists research.milestone_activities (
  milestone_id integer not null references research.milestones(id),
  activity_id  integer not null references research.activities(id),
  primary key (milestone_id, activity_id)
);

create table if not exists research.documents (
  id          integer generated by default as identity primary key,
  project_id  integer references research.projects(id),
  activity_id integer references research.activities(id),
  title       varchar(250) not null,
  kind        varchar(20) not null check (kind in ('project','evidence','institutional')),
  blocked     smallint not null default 0,
  restricted  smallint not null default 0,
  created_by  integer references research.users(id),
  deleted_at  timestamptz,
  created_at  timestamptz not null default now()
);
alter table research.documents add column if not exists created_by integer references research.users(id);

create table if not exists research.document_versions (
  id           integer generated by default as identity primary key,
  document_id  integer not null references research.documents(id),
  version      integer not null,
  filename     varchar(255) not null,
  mime         varchar(100) not null,
  size_bytes   integer not null default 0,
  note         text,
  content      bytea not null,
  text_content text,
  uploaded_by  integer not null references research.users(id),
  created_at   timestamptz not null default now(),
  unique (document_id, version)
);
alter table research.document_versions add column if not exists size_bytes integer not null default 0;
alter table research.document_versions add column if not exists note text;

-- Fragmentos de texto indexados para el asistente (RAG con búsqueda de texto completo).
create table if not exists research.document_chunks (
  id          integer generated by default as identity primary key,
  document_id integer not null references research.documents(id),
  version     integer not null,
  fragment    integer not null,
  content     text not null,
  tsv         tsvector not null
);
create index if not exists document_chunks_doc_idx on research.document_chunks (document_id, version);
create index if not exists document_chunks_tsv_idx on research.document_chunks using gin (tsv);

create table if not exists research.closures (
  id                  integer generated by default as identity primary key,
  project_id          integer not null references research.projects(id),
  requested_by        integer not null references research.users(id),
  observations        text,
  status              varchar(30) not null default 'pending' check (status in ('pending','approved','changes_requested')),
  review_observations text,
  reviewed_by         integer references research.users(id),
  created_at          timestamptz not null default now(),
  reviewed_at         timestamptz
);

create table if not exists research.project_history (
  id         integer generated by default as identity primary key,
  project_id integer not null references research.projects(id),
  actor_id   integer not null references research.users(id),
  entity     varchar(40) not null,
  entity_id  integer not null,
  action     varchar(80) not null,
  details    text,
  created_at timestamptz not null default now()
);
create index if not exists project_history_project_idx on research.project_history (project_id, entity, entity_id);

-- Bitácora del asistente (pregunta y fuentes; sirve para auditar que respetó permisos).
create table if not exists research.assistant_log (
  id         integer generated by default as identity primary key,
  user_id    integer not null references research.users(id),
  project_id integer,
  question   text not null,
  mode       varchar(20) not null,
  created_at timestamptz not null default now()
);

-- Seguridad: nadie entra al esquema research desde la API pública.

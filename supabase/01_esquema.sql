-- =====================================================================
-- Migración a la versión 3 (sin evaluador). Es segura de repetir.
-- =====================================================================
-- Estados permitidos: primero se quita la regla vieja, se convierten los datos y se pone la nueva.
alter table research.users drop constraint if exists users_role_check;
alter table research.projects drop constraint if exists projects_status_check;
alter table research.activities drop constraint if exists activities_status_check;

-- Las cuentas de evaluador pasan a investigador INACTIVO: Coordinación decide si las reactiva.
update research.users set role = 'researcher', status = 'inactive', updated_at = now() where role = 'evaluator';
update research.user_sessions set revoked_at = now()
  where revoked_at is null and user_id in (select id from research.users where status = 'inactive');

-- Propuestas: un solo estado "Cambios solicitados" que recuerda a quién regresa.
update research.proposals set status = 'changes_requested', returns_to = 'pending_researcher_review'
  where status = 'changes_requested_researcher';
update research.proposals set status = 'changes_requested', returns_to = 'pending_coordinator'
  where status = 'changes_requested_evaluator';
update research.proposals set status = 'pending_coordinator' where status = 'under_evaluation';
-- Las archivadas pasan a "Cancelada" y se pueden reactivar.
update research.proposals set
    status_before_cancel = case coalesce(status_before_archive, status)
      when 'changes_requested_researcher' then 'pending_researcher_review'
      when 'changes_requested_evaluator' then 'pending_coordinator'
      when 'under_evaluation' then 'pending_coordinator'
      when 'changes_requested' then coalesce(returns_to, 'pending_coordinator')
      else coalesce(status_before_archive, status) end,
    status = 'cancelled', is_archived = 0, status_before_archive = null
  where is_archived = 1;

-- Actividades: ya no existe el paso "Comenzar".
update research.activities set status = case when observations is not null and btrim(observations) <> '' then 'changes' else 'pending' end
  where status = 'in_progress';

alter table research.users add constraint users_role_check check (role in ('student','researcher','coordinator'));
alter table research.projects add constraint projects_status_check
  check (status in ('active','changes','closing','finalized','cancelled'));
alter table research.activities add constraint activities_status_check
  check (status in ('pending','in_review','changes','completed','cancelled'));


